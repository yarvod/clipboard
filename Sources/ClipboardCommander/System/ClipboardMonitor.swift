import AppKit

/// Следит за системным буфером.
///
/// Раз в полсекунды сравнивает `changeCount` — это одно целое число, без чтения содержимого,
/// поэтому опрос почти ничего не стоит. Содержимое читается только когда буфер реально изменился.
@MainActor
final class ClipboardMonitor {
    /// Метка, которой мы помечаем собственные записи в буфер, чтобы не ловить их повторно.
    static let ownType = NSPasteboard.PasteboardType("com.yarvod.clipboardcommander.own")

    /// Типы, которыми менеджеры паролей и другие программы просят не сохранять содержимое.
    /// См. http://nspasteboard.org
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
        ownType.rawValue,
    ]

    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png,
        NSPasteboard.PasteboardType("public.jpeg"),
        NSPasteboard.PasteboardType("public.heic"),
        .tiff,
    ]

    private static let maxTextBytes = 10 * 1024 * 1024
    private static let maxImageBytes = 100 * 1024 * 1024

    private let pasteboard = NSPasteboard.general
    private let store: HistoryStore
    private var lastChangeCount: Int
    private var timer: Timer?

    init(store: HistoryStore) {
        self.store = store
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.poll()
            }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard let types = pasteboard.types, !types.isEmpty else { return }
        let names = Set(types.map(\.rawValue))
        guard names.isDisjoint(with: Self.ignoredTypes) else { return }
        // Скопированные в Finder файлы не храним: в буфере лишь ссылки на них.
        guard !names.contains(NSPasteboard.PasteboardType.fileURL.rawValue) else { return }

        let source = frontmostSource()
        let imageType = Self.imageTypes.first { names.contains($0.rawValue) }
        let text = pasteboard.string(forType: .string)

        // Текст важнее картинки (таблицы и документы кладут оба варианта),
        // кроме случая «скопировать изображение» в браузере, где рядом лежит только ссылка.
        if let text,
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
           !(imageType != nil && Self.isBareURL(text))
        {
            guard text.utf8.count <= Self.maxTextBytes else { return }
            store.addText(text, source: source)
        } else if let imageType,
                  let data = pasteboard.data(forType: imageType),
                  data.count <= Self.maxImageBytes
        {
            store.addImage(data: data, uti: imageType.rawValue, source: source)
        }
    }

    private func frontmostSource() -> SourceApp? {
        guard let app = NSWorkspace.shared.frontmostApplication,
              app.bundleIdentifier != Bundle.main.bundleIdentifier
        else { return nil }
        return SourceApp(name: app.localizedName, bundleID: app.bundleIdentifier)
    }

    private static func isBareURL(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return !trimmed.contains(where: \.isWhitespace)
            && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
    }
}
